#!/usr/bin/env python3
"""gen_nrth_audit_sigs_h.py — regenerate src/nrth_audit_sigs.h from the extracted
signature catalogue so the compiled detection table can never drift from the evidence.

Usage:
    python3 tools/nrth_sig_export.py <NRTH.dll> working/sigs.json
    python3 tools/gen_nrth_audit_sigs_h.py working/sigs.json src/nrth_audit_sigs.h

Only High-confidence entries (the record was reassembled from a real decryptor call site
in the sample) are emitted. Medium-confidence candidates stay in the JSON + case report.
"""
import json
import sys

# role text per "owner" routine of the signature record, keyed by the owner function VA
ROLES = {
    "0x10005b80": ("client.dll",
                   "Lua-VM / client interface hook installed by the resolver at 0x10005b80 "
                   "(11 pattern scans + 11 MH_CreateHook calls there)"),
    "0x1000c390": ("client.dll",
                   "offset/pointer resolver at 0x1000c390: locates functions, installs no "
                   "hook of its own"),
}
DEFAULT_ROLE = ("netc.dll",
                "located in the netc.dll 'check kill' cluster (one-byte 0xC3 writes through "
                "the writer at 0x10011870, 6 call sites)")

HDR = '''/**
 * ============================================================================
 * nrth_audit_sigs.h — GENERATED FILE, do not edit by hand
 * ============================================================================
 * Generated by tools/gen_nrth_audit_sigs_h.py from the catalogue produced by
 * tools/nrth_sig_export.py against the ORIGINAL sample
 *   NRTH.dll  SHA-256 947b81be2d0f84cc5f51742ef8e9dbf6183597ed98afaf1377bfc4352e007861
 *   ImageBase 0x10000000
 *
 * Every entry is a plaintext byte-signature that the sample keeps obfuscated and uses to
 * find a function in an MTA:SA module *by code pattern* (those functions are not exported
 * by name). Fields: signature length, pattern text, target module, role, VA of the
 * decryptor call that materialises the record, the pattern-text length, the
 * positional-XOR key (plain[p] = cipher[p] ^ ((p - key) & 0xFF)), and confidence
 * (2 = High: reassembled from the code path; 1 = Medium).
 *
 * This is detection data for integrity checking only. Nothing here is used to hook,
 * patch, inject or execute anything.
 * ============================================================================
 */
#ifndef NRTH_AUDIT_SIGS_H
#define NRTH_AUDIT_SIGS_H

#include "nrth_audit.h"

#define NRTH_SIG_COUNT {count}

static const NrthSignature g_NrthSigTable[NRTH_SIG_COUNT] = {
{rows}
};

#endif /* NRTH_AUDIT_SIGS_H */
'''


def main(sigjson, outpath):
    data = json.load(open(sigjson))
    rows, n = [], 0
    for s in data["signatures"]:
        if s["confidence"] != "High":
            continue
        owner = s.get("owner_func") or "?"
        mod, role = ROLES.get(owner, DEFAULT_ROLE)
        if s.get("module"):
            mod = s["module"]
        dec = ("0x%08x" % int(s["decryptor"], 16)) if s["decryptor"] not in ("-", None) else "0"
        key = ("0x%02X" % int(s["xor_key"], 16)) if s["xor_key"] not in ("-", None) else "0"
        sites = " ".join(s["code_sites"])
        n += 1
        rows.append(
            '    { %d, "%s",\n'
            '      "%s",\n'
            '      "%s",\n'
            '      %s, %d, %s, 2 /* High */, "%s" }'
            % (n, s["pattern"].replace("\\", "\\\\").replace('"', '\\"'),
               mod, role.replace('"', "'"), dec, s["len"], key, sites))
    text = HDR.replace("{count}", str(n)).replace("{rows}", ",\n".join(rows))
    with open(outpath, "w") as f:
        f.write(text)
    print("[+] %s: %d High-confidence signature rows" % (outpath, n))
    return 0


if __name__ == "__main__":
    # defaults match the repo layout, so `build_audit.sh --regen` needs no arguments
    a = sys.argv[1:]
    sys.exit(main(a[0] if a else "../working/sigs.json",
                  a[1] if len(a) > 1 else "src/nrth_audit_sigs.h"))

#!/usr/bin/env python3
"""nrth_case_strings.py — regenerate mta_blue_team_case/detection/recovered_strings.txt.

Input: working/recovered.json (from tools/nrth_strings_recover.py) and working/sigs.json
(from tools/nrth_sig_export.py), plus the case folder's plain-string catalog so each entry can
be labelled honestly: "was this already visible in the file, or only after decoding?"

Nothing is asserted here that is not in the JSON evidence files: run the two tools first.
The generated text file is deliberately plain (no markdown) so it can be fed to grep/EDR
rule-building directly.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RECOVERED = os.path.join(ROOT, "working", "recovered.json")
SIGS = os.path.join(ROOT, "working", "sigs.json")
CATALOG = os.path.join(ROOT, "mta_blue_team_case", "strings_catalog.txt")
OUT = os.path.join(ROOT, "mta_blue_team_case", "detection", "recovered_strings.txt")

INTEREST = (".dll", ".cfg", ".ini", "\\", ":", "Error", "no_spoofer", "menu_key", "screen",
            "position", "velocity", "serial", "crash", "Registry", "Software", "CLSID",
            "Connections", "Scripts", "auto_inject", "@")


def load(p):
    with open(p) as f:
        return json.load(f)


def main():
    for p in (RECOVERED, SIGS):
        if not os.path.exists(p):
            sys.exit("[!] missing evidence file %s — run tools/nrth_strings_recover.py "
                     "and tools/nrth_sig_export.py first" % p)
    rec = load(RECOVERED)
    sig = load(SIGS)
    plain = set()
    if os.path.exists(CATALOG):
        with open(CATALOG, encoding="utf-8", errors="replace") as f:
            for line in f:
                if line.startswith("Offset:") and '"' in line:
                    plain.add(line.rsplit('"', 2)[1] if line.count('"') >= 2 else "")
    seen = set()
    lines = []
    w = lines.append

    w("# NRTH.dll — plaintexts recovered from the sample's own string decryptors")
    w("#")
    w("# sample        : %s" % rec["file"].split("/")[-1])
    w("# codec         : %s" % rec["codec"])
    w("# source of truth: working/recovered.json (tools/nrth_strings_recover.py, capstone)")
    w("# generated by  : recovered_or_reconstructed_project/tools/nrth_case_strings.py")
    w("#")
    w("# Meaning of the columns")
    w("#   VA        = address of the *call site* that decrypts the record (not of the data)")
    w("#   dec       = address of the decryptor function (one per record length)")
    w("#   key       = the per-decryptor constant K in  plain[p] = cipher[p] ^ ((p-K)&0xFF)")
    w("#   visibility: HIDDEN  = the plaintext does not appear anywhere in strings_catalog.txt,")
    w("#                         i.e. only the decoder reveals it (this is the useful half)")
    w("#             PLAIN+REC = also present as a plain string in the image")
    w("#")
    w("# No claim below is inferred from naming: each line is a byte-exact decode of bytes in")
    w("# the sample. Interpretations (why a string exists) are NOT included here; see")
    w("# mechanism_overview_ar.md and report.md for those, with their own confidence tags.")
    w("")

    # Classify each decode so the case file never mixes evidence with artefacts:
    #   SIGNATURE = x86 pattern text (hex tokens with '?' wildcards)
    #   STRING    = looks like a path/registry key/word (printable, no shell-noise chars)
    #   NOISE     = everything else: records whose ciphertext is relocated/filled at run
    #               time, or where several keys decode to equally printable text. Those are
    #               kept and labelled, not dropped, but they are NOT indicators.
    import re
    sig_re = re.compile(r"^(?:[0-9A-F?]{1,2} )+[0-9A-F?]{1,2}$")
    ok_re = re.compile(r"^[ -~]+$")
    bad_re = re.compile(r"[\[\]^`{|}~]")   # "_" is common in real identifiers, so it stays
    # real operator-facing text is lower-case-heavy; a wrong key produces runs of random
    # upper-case letters, which is what this ratio separates
    texty_re = re.compile(r"[a-z .:/\\_#%\-0-9]")

    def classify(t):
        if sig_re.match(t):
            return "SIGNATURE"
        if not t or not ok_re.match(t) or bad_re.search(t):
            return "NOISE"
        if len(t) >= 4 and sum(1 for c in t if texty_re.match(c)) * 10 >= len(t) * 7:
            return "STRING"
        return "NOISE"

    recs = rec["records"]
    hidden, also, noise = [], [], []
    for r in recs:
        t = r["text"]
        r["class"] = classify(t)
        if t in seen:
            continue
        seen.add(t)
        if r["class"] == "NOISE":
            noise.append(r)
        elif t in plain:
            also.append(r)
        else:
            hidden.append(r)

    w("=" * 78)
    w("SECTION A — usable plaintexts only reachable through the decryptors (%d records)"
      % len(hidden))
    w("=" * 78)
    w("%-13s %-13s %-6s %-5s %-10s %s" % ("VA", "dec", "key", "len", "kind", "plaintext"))
    w("-" * 78)
    for r in sorted(hidden, key=lambda x: (-x["len"], x["text"])):
        w("%-13s %-13s %-6s %-5s %-10s %s" % (r["site"], r["decryptor"], r["key"], r["len"],
                                              r["class"], r["text"]))
    w("")
    w("A.1 high-value subset (detection candidates, module paths / config / telemetry):")
    for r in hidden:
        if any(k in r["text"] for k in INTEREST) and len(r["text"]) >= 8:
            w("    [%s key %s] %s" % (r["site"], r["key"], r["text"]))
    w("")

    w("=" * 78)
    w("SECTION A' — decodes that are NOT usable as indicators (%d records)" % len(noise))
    w("=" * 78)
    w("Why they are separated: the sample builds several of these records at run time (the")
    w("ciphertext is fetched from a .data global by a helper such as 0x10023670, so the bytes")
    w("in the file image are not the final input) and for short records more than one key can")
    w("produce printable text. Listing them keeps the record count honest (82 decryptors /")
    w("%d records) while making clear that only Sections A and C are evidence." % len(recs))
    for r in noise:
        w("    [%s dec=%s key=%s len=%s] %r" % (r["site"], r["decryptor"], r["key"], r["len"],
                                                r["text"]))
    w("")

    w("=" * 78)
    w("SECTION B — records whose plaintext is ALSO visible as a plain string (%d)" % len(also))
    w("=" * 78)
    w("(listed for completeness; these are not 'hidden' and add no new indicator value)")
    for r in also:
        w("    %s" % r["text"])
    w("")

    w("=" * 78)
    w("SECTION C — code signatures the tool searches for in other modules")
    w("=" * 78)
    sigs = sig["signatures"]
    hi = [s for s in sigs if s["confidence"] == "High"]
    md = [s for s in sigs if s["confidence"] != "High"]
    w("These are x86 pattern strings (with '?' wildcards) that NRTH.dll decrypts at runtime and")
    w("hands to its module scanner/resolver (0x10002960) to locate functions in client.dll /")
    w("netc.dll. They are *not* strings that belong to MTA itself, which is exactly what makes")
    w("them usable as memory-integrity anchors: find the function by the pattern, then look at")
    w("its first bytes (PRISTINE vs E9/FF 25/C3).")
    w("")
    w("C.1 High confidence — recovered from a decryptor record, module + owner function known")
    w("    (%d entries; %s also compiles them into the audit module)" %
      (len(hi), "src/nrth_audit_sigs.h"))
    for s in hi:
        w("    [%s] owner=%s module=%s len=%s key=%s" %
          (s["code_sites"][0] if s["code_sites"] else "-", s.get("owner_func", "-"),
           s.get("module") or "-", s["len"], s["xor_key"]))
        w("        %s" % s["pattern"])
    w("")
    w("C.2 Medium confidence — found by the prologue-anchored sweep of .data (runtime state of")
    w("    the netc.dll patch cluster). These are the *targets of the 0xC3 writes*, i.e. the")
    w("    MTA client/network functions the cheat disables. Over-reads are possible (the sweep")
    w("    cannot know the record length), so trailing tokens such as 'B900' are noise.")
    for s in md:
        w("    [%s] module=%s len=%s key=%s" % (", ".join(s["data_sites"]),
                                                s.get("module") or "-", s["len"], s["xor_key"]))
        w("        %s" % s["pattern"])
    w("")
    w("=" * 78)
    w("SECTION E — two run-time identifiers worth knowing about, verified outside the JSON")
    w("=" * 78)
    w("  @custom       PLAIN string at .rdata file offset 0x000e9890 (VA 0x100e9890); it is")
    w("                already visible in strings_catalog.txt line 6091. Role (Lua chunk name")
    w("                for the menu's Execute path) is Strongly inferred from 0x10004550.")
    w("  @auto_inject  NOT present as a plain string. It is built from inline immediates on")
    w("                the stack at the auto-inject path near 0x100044df and decrypts with")
    w("                K=0x20; the ciphertext bytes and the decode are frozen as check 3 of")
    w("                NrthAuditSelfTest() (src/nrth_audit.cpp), so `nrth_audit selftest`")
    w("                re-verifies it on every run: 93 b5 a0 a2 b8 87 b0 b4 b1 b9 be aa.")
    w("  C:\\NVX        a plain .rdata string (file offset 0x000afd18) that does NOT appear in")
    w("                any decryptor record. Earlier case text implied the config path came")
    w("                from an encrypted record — it does not: the config path the payload")
    w("                actually decrypts is C:\\Overwack\\loader_config.cfg (Section A).")
    w("")

    w("=" * 78)
    w("SECTION D — how to reproduce / how to use this file")
    w("=" * 78)
    w("    cd recovered_or_reconstructed_project")
    w("    python3 tools/nrth_strings_recover.py ../../working/NRTH.dll -o ../../working/recovered.json")
    w("    python3 tools/nrth_sig_export.py      ../../working/NRTH.dll -o ../../working/sigs.json")
    w("    python3 tools/nrth_case_strings.py            # regenerates this file")
    w("")
    w("Detection use:")
    w("  * Section A gives file/hash-independent strings for the *loader's* config path and for")
    w("    the ADS/cache locations — see detection/telemetry.md Layer 1.")
    w("  * Section C.1 is what NRTH_audit.dll scans with; the YARA rules in yara_rules.yar carry")
    w("    a subset of the same patterns for scan-time use (YARA cannot do the widen/patch logic).")
    w("  * Section C.2 must NOT be used as a cheat-presence indicator on its own: those prologue")
    w("    shapes are ordinary MSVC __SEH_prolog4 / __GS-setup code and appear in many modules.")
    w("    They are useful as *the location to memory-integrity check* once the cheat is known.")

    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("[+] wrote %s (%d lines, %d hidden records, %d signatures)" %
          (OUT, len(lines), len(hidden), len(sigs)))


if __name__ == "__main__":
    main()
